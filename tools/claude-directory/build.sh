#!/usr/bin/env bash
# Builds the Claude.ai directory plugin tree into <output-dir>.
#
# The Anthropic plugin directory accepts only Markdown, text, JSON, YAML and a
# few image types from organizations that are not Verified. This script copies
# a fixed allowlist, never a pattern over the repo, so a file added to the
# repository later cannot reach the directory by accident. check.sh enforces
# the directory's rules on the result.
#
# Usage: tools/claude-directory/build.sh <output-dir>
#   <output-dir> must not exist, or must be empty.
set -euo pipefail

if [ "$#" -ne 1 ]; then
  echo "usage: $0 <output-dir>" >&2
  exit 2
fi

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$1"

if [ -d "$OUT" ] && [ -n "$(ls -A "$OUT")" ]; then
  echo "error: output directory is not empty: $OUT" >&2
  exit 1
fi
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"

# copy_file <path relative to the repo root> <path relative to the output dir>
copy_file() {
  local src="$ROOT/$1" dest="$OUT/$2"
  if [ -L "$src" ]; then
    echo "error: symlinks are not allowed in the directory build: $1" >&2
    exit 1
  fi
  if [ ! -f "$src" ]; then
    echo "error: missing source file: $1" >&2
    exit 1
  fi
  mkdir -p "$(dirname "$dest")"
  cp "$src" "$dest"
}

copy_file ".claude-plugin/plugin.json" ".claude-plugin/plugin.json"
copy_file ".claude-plugin/icon.png" ".claude-plugin/icon.png"
copy_file "LICENSE" "LICENSE"
copy_file "tools/claude-directory/README.md" "README.md"

# Every git-tracked file under skills/ (skills/ is generated by
# tools/build-skills.sh and committed). Untracked files, such as editor or OS
# leftovers, are never copied.
skill_files=0
while IFS= read -r -d '' rel; do
  copy_file "$rel" "$rel"
  skill_files=$((skill_files + 1))
done < <(git -C "$ROOT" ls-files -z -- skills)

if [ "$skill_files" -eq 0 ]; then
  echo "error: no tracked files under skills/" >&2
  exit 1
fi

total="$(find "$OUT" -type f | wc -l | tr -d ' ')"
echo "Built $total files into $OUT"
